  function byId(list, id) {
    for (var i = 0; i < list.length; i++) if (list[i].id === id) return list[i];
    return list[0];
  }

  function parts(audId, taskId) {
    var task = byId(TASKS, taskId);
    var spec = task.by[audId] || task.by[AUD[0].id];
    return {
      title: byId(AUD, audId).label + ' · ' + task.label,
      summary: task.lead + ' ' + spec.focus,
      stack: [['Данные', spec.data], ['Модель', task.model], ['Канал доставки', spec.channel]],
      steps: task.steps,
      need: task.need.map(function (item) { return item.replace('{данные}', spec.data); })
    };
  }

  // Every element that fades in gets --i: its position in the reveal order.
  function cardHTML(audId, taskId) {
    var p = parts(audId, taskId);
    var i = 0;
    function ln(tag, cls, html) {
      return '<' + tag + ' class="brief__ln' + (cls ? ' ' + cls : '') + '" style="--i:' + i++ + '">' + html + '</' + tag + '>';
    }
    var html = ln('p', 'brief__kicker', p.title) + ln('p', 'brief__summary', p.summary);
    html += '<div class="brief__stack">' + p.stack.map(function (row) {
      return ln('div', 'brief__unit', '<p class="brief__term">' + row[0] + '</p><p>' + row[1] + '</p>');
    }).join('') + '</div>';
    html += '<div class="brief__cols"><div class="brief__col">';
    html += ln('p', 'brief__term', 'Этапы работ');
    html += '<ol class="brief__list brief__list--num">' + p.steps.map(function (s) { return ln('li', '', s); }).join('') + '</ol>';
    html += '</div><div class="brief__col">';
    html += ln('p', 'brief__term', 'Что нужно от вас');
    html += '<ul class="brief__list">' + p.need.map(function (s) { return ln('li', '', s); }).join('') + '</ul>';
    return html + '</div></div>';
  }

  // The same brief as plain text — this is what lands in the lead form.
  function briefText(audId, taskId) {
    var p = parts(audId, taskId);
    return p.title + '\n\n' + p.summary + '\n\n'
      + p.stack.map(function (row) { return row[0] + ': ' + row[1]; }).join('\n') + '\n\n'
      + 'Этапы работ:\n' + p.steps.map(function (s, n) { return (n + 1) + '. ' + s; }).join('\n') + '\n\n'
      + 'Что нужно с нашей стороны:\n' + p.need.map(function (s) { return '— ' + s; }).join('\n');
  }

  /* --- wiring --- */

  var root = document.getElementById('brief');
  var out = document.getElementById('brief-result');
  if (!root || !out) return;

  // Must match the static markup the page ships with, so nothing redraws on load.
  var state = { aud: 'museum', task: 'assistant' };

  root.addEventListener('click', function (e) {
    var btn = e.target.closest('button[data-aud], button[data-task]');
    if (!btn) return;
    var key = btn.dataset.aud ? 'aud' : 'task';
    var value = btn.dataset.aud || btn.dataset.task;
    if (state[key] === value) return;
    state[key] = value;
    var group = btn.parentNode.querySelectorAll('button');
    for (var i = 0; i < group.length; i++) group[i].setAttribute('aria-pressed', String(group[i] === btn));
    out.innerHTML = cardHTML(state.aud, state.task);
  });

  var cta = document.getElementById('brief-go');
  var field = document.querySelector('#lead-form textarea[name="task"]');
  if (!cta || !field) return; // without the form the button stays a plain anchor to #form

  cta.addEventListener('click', function (e) {
    e.preventDefault();
    field.value = briefText(state.aud, state.task);
    var calm = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    document.getElementById('lead-form').scrollIntoView({ behavior: calm ? 'auto' : 'smooth', block: 'start' });
    field.focus({ preventScroll: true });
  });
